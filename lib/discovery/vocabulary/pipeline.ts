/**
 * Speak Better — live vocabulary discovery.
 *
 * The pipeline, in the order the stages actually run:
 *
 *   Discover → Normalize → Enrich → Evaluate → Validate → Approve → (store) → Publish
 *
 * WHAT IT IS
 * A scheduled server-side job. It asks Datamuse for words related to a rotating
 * set of anchors, checks each candidate against Wiktionary and the Free Dictionary
 * API, estimates difficulty from corpus frequency, and *approves* a lesson only
 * when an editor has already written a gloss for it and every quality gate passes.
 * Approved lessons are written to the existing Curiosity candidate reservoir
 * (`curiosity_candidates`, category `speak-better`); the publisher then reads the
 * reservoir and never calls a lexical API while a reader is on the page.
 *
 * WHAT IT IS NOT
 * It is not an author. No Hindi meaning, nuance note, learner mistake or speaking
 * challenge is generated by a model, because this application has no language model
 * and inventing one's output would be the single worst thing this pipeline could
 * do to a learner. A discovered word without a gloss is stored as `needs-review`:
 * it is visible in the run report and never shown as a lesson.
 *
 * FAILURE BEHAVIOUR
 * Every source call is bounded and every failure is a value. One source down still
 * yields a lesson from the others (and the lesson says which failed); every source
 * down yields *no* approval, and the publisher falls back to the authored
 * curriculum. Nothing here can empty the Curiosity page.
 */


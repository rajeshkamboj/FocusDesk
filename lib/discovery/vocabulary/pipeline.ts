/** The bands the default experience targets. A C2 word is allowed, occasionally. */
export const VOCABULARY_TARGET_BANDS: readonly SpeakBetterLevel[] = ['B2', 'C1', 'C2'];

/**
 * The frequency → band table.
 *
 * Stated in full because it is a judgement, not a measurement: no free source
 * publishes CEFR levels per word, so the pipeline maps Datamuse's per-million
 * frequency onto a band and says so on the lesson (`levelBasis:
 * 'estimated-frequency'`). Frequencies are corpus observations, not curriculum
 * decisions; the editor's band is recorded separately and wins when frequency is
 * unavailable.
 */
export const FREQUENCY_BANDS: readonly { min: number; band: SpeakBetterLevel | 'rare' | 'too-common' }[] = [
  { min: 250, band: 'too-common' },
  { min: 100, band: 'A2-B1' },
  { min: 30, band: 'B2' },
  { min: 8, band: 'C1' },
  { min: 1, band: 'C2' },
  { min: 0, band: 'rare' },
];

export function estimateBand(frequencyPerMillion: number | undefined): SpeakBetterLevel | 'rare' | 'too-common' | null {
  if (frequencyPerMillion === undefined || !Number.isFinite(frequencyPerMillion)) return null;
  for (const row of FREQUENCY_BANDS) {
    if (frequencyPerMillion >= row.min) return row.band;
  }
  return 'rare';
}


const DEVANAGARI = /[\u0900-\u097F]/;

function minLength(value: string | undefined, minimum: number): boolean {
  return typeof value === 'string' && value.trim().length >= minimum;
}

/**
 * The editorial gate.
 *
 * These are the checks that make a lesson *teachable* rather than merely valid
 * data: a natural Hindi gloss in Devanagari, enough adult examples, a stated
 * register and a real learner mistake. They are deliberately strict; a word that
 * fails here is not published with blanks, it waits.
 */
export function glossRejections(gloss: VocabularyGloss | undefined): string[] {
  if (!gloss) return ['no editorial gloss: this word cannot be taught until an editor writes one'];
  const reasons: string[] = [];
  if (!isTeachableWord(gloss.word)) reasons.push('the target is not a single teachable English word');
  if (!VOCABULARY_TARGET_BANDS.includes(gloss.level)) {
    reasons.push(`editorial band ${gloss.level} is outside the B2–C2 target`);
  }
  if (!minLength(gloss.englishMeaning, 20)) reasons.push('English meaning is missing or too short');
  if (!minLength(gloss.hindiMeaning, 2) || !DEVANAGARI.test(gloss.hindiMeaning)) {
    reasons.push('Hindi meaning is missing or is not written in Devanagari');
  }
  if (!minLength(gloss.nuance, 40)) reasons.push('nuance note is missing or too short');
  if (!Array.isArray(gloss.examples) || gloss.examples.length < 2) {
    reasons.push('two practical examples are required');
  } else if (gloss.examples.some((example) => example.trim().length < 20 || example.trim().length > 240)) {
    reasons.push('an example is too short to be adult usage, or too long to read on a card');
  }
  if (!minLength(gloss.register, 12)) reasons.push('register note is missing');
  if (!minLength(gloss.commonMistake, 20)) reasons.push('common mistake is missing');
  if (!minLength(gloss.focus, 12)) reasons.push('focus line is missing');
  if (!minLength(gloss.situation, 12)) reasons.push('situation is missing');
  if (!minLength(gloss.challenge, 15)) reasons.push('challenge is missing');
  if (!Array.isArray(gloss.collocations) || gloss.collocations.length < 1) {
    reasons.push('at least one collocation is required');
  }
  if (!Array.isArray(gloss.dialogue) || gloss.dialogue.length < 2) {
    reasons.push('a two-line dialogue is required');
  }
  return reasons;
}

export interface VocabularyEvaluation {
  band: SpeakBetterLevel | null;
  levelBasis: 'curated' | 'estimated-frequency';
  quality: string[];
  rejections: string[];
}

/**
 * Evaluate usefulness and difficulty.
 *
 * A word is rejected when it is *too common to teach* at this level or too rare to
 * be worth an adult's attention. Frequency is the evidence; when it is missing the
 * editor's band is used and the loss is recorded, never guessed.
 */
export function evaluateCandidate(
  gloss: VocabularyGloss,
  evidence: { frequencyPerMillion?: number; hasLexicalDefinition: boolean },
): VocabularyEvaluation {
  const quality: string[] = [];
  const rejections: string[] = [];
  const estimate = estimateBand(evidence.frequencyPerMillion);

  let band: SpeakBetterLevel = gloss.level;
  let levelBasis: 'curated' | 'estimated-frequency' = 'curated';

  if (estimate === 'too-common' || estimate === 'A2-B1') {
    rejections.push(`too common for a B2–C1 target (${evidence.frequencyPerMillion} occurrences per million)`);
  } else if (estimate === 'rare') {
    rejections.push(`too rare to be worth a lesson (${evidence.frequencyPerMillion} occurrences per million)`);
  } else if (estimate === 'B2' || estimate === 'C1' || estimate === 'C2') {
    band = estimate;
    levelBasis = 'estimated-frequency';
    quality.push(`frequency ${evidence.frequencyPerMillion}/million → ${estimate}`);
  } else {
    quality.push('frequency unavailable, so the editor’s band is used and the lesson says so');
  }

  if (!VOCABULARY_TARGET_BANDS.includes(band)) {
    rejections.push(`band ${band} is outside the B2–C2 target`);
  }
  if (!evidence.hasLexicalDefinition) {
    rejections.push('no lexical source confirmed the word, so it cannot be published as verified vocabulary');
  }
  if (gloss.examples.length >= 2) quality.push(`${gloss.examples.length} adult examples`);
  if (gloss.differsFrom) quality.push('distinguishes a near-synonym');
  if (gloss.collocations.length >= 2) quality.push(`${gloss.collocations.length} collocations`);
  if (gloss.level !== band && levelBasis === 'estimated-frequency') {
    quality.push(`editorial band ${gloss.level} overridden by measured frequency ${band}`);
  }

  return { band, levelBasis, quality, rejections };
}


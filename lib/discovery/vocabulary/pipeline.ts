export function vocabularyLessonId(word: string): string {
  return `vocab-${normalizeTitle(word).replace(/\s+/g, '-')}`;
}

function firstUsable<T>(...values: (T | undefined)[]): T | undefined {
  return values.find((value) => value !== undefined);
}

/**
 * Assemble the lesson.
 *
 * Authored fields come from the gloss; dictionary fields are attached as one
 * clearly-attributed `dictionary` object, exactly as the authored lessons do it.
 * A reader can therefore tell which sentence is our judgement and which is a
 * dictionary's.
 */
export function buildLesson(
  gloss: VocabularyGloss,
  evidence: {
    band: SpeakBetterLevel;
    levelBasis: 'curated' | 'estimated-frequency';
    frequencyPerMillion?: number;
    quality: string[];
    sources: VocabularySourceRef[];
    wiktionary?: { definition?: string; partOfSpeech?: string; url: string; license: string; sourceName: string };
    freeDictionary?: {
      definition?: string;
      partOfSpeech?: string;
      phonetic?: string;
      url: string;
      license: string;
      sourceName: string;
    };
    related: string[];
  },
  approvedOn: string,
): SpeakBetterLesson {
  const definition = firstUsable(evidence.freeDictionary?.definition, evidence.wiktionary?.definition);
  const pronunciation = evidence.freeDictionary?.phonetic ?? gloss.pronunciation;
  const dictionaryUrl = firstUsable(evidence.wiktionary?.url, evidence.freeDictionary?.url)
    ?? `https://en.wiktionary.org/wiki/${encodeURIComponent(gloss.word)}`;

  const dictionary = definition
    ? {
        sourceName: firstUsable(evidence.wiktionary?.sourceName, evidence.freeDictionary?.sourceName) ?? 'Wiktionary',
        license: [evidence.wiktionary?.license, evidence.freeDictionary?.license].filter(Boolean).join(' · ')
          || 'Wiktionary, CC BY-SA 4.0',
        url: dictionaryUrl,
        ...(pronunciation ? { pronunciation } : {}),
        ...(firstUsable(evidence.freeDictionary?.partOfSpeech, evidence.wiktionary?.partOfSpeech)
          ? { partOfSpeech: firstUsable(evidence.freeDictionary?.partOfSpeech, evidence.wiktionary?.partOfSpeech) }
          : {}),
        definition,
        ...(evidence.related.length ? { collocations: [...new Set([...gloss.collocations, ...evidence.related])].slice(0, 6) } : { collocations: gloss.collocations }),
        fetchedAt: approvedOn,
      }
    : undefined;

  const failedSources = evidence.sources.filter((source) => source.status === 'failed');
  const word = {
    id: `${vocabularyLessonId(gloss.word)}:${gloss.word}`,
    word: gloss.word,
    partOfSpeech: gloss.partOfSpeech,
    tone: gloss.tone,
    englishMeaning: gloss.englishMeaning,
    hindiMeaning: gloss.hindiMeaning,
    nuance: gloss.nuance,
    examples: gloss.examples,
    ...(pronunciation ? { pronunciation } : {}),
    collocations: gloss.collocations,
    commonMistake: gloss.commonMistake,
    ...(gloss.differsFrom ? { differsFrom: gloss.differsFrom } : {}),
    register: gloss.register,
    ...(dictionary ? { dictionary } : {}),
  };

  return {
    id: vocabularyLessonId(gloss.word),
    level: evidence.band,
    levelBasis: evidence.levelBasis,
    origin: 'discovered',
    focus: gloss.focus,
    situation: gloss.situation,
    word,
    dialogue: gloss.dialogue,
    challenge: gloss.challenge,
    enrichment: {
      status: dictionary ? 'enriched' : 'unavailable',
      detail: dictionary
        ? `dictionary detail from ${dictionary.sourceName}${failedSources.length ? `; ${failedSources.map((source) => source.name).join(', ')} did not answer` : ''}`
        : 'authored lesson; no dictionary service answered',
      fetchedAt: approvedOn,
    },
    discovery: {
      approvedOn,
      sources: evidence.sources,
      levelBasis: evidence.levelBasis,
      ...(evidence.frequencyPerMillion !== undefined ? { frequencyPerMillion: evidence.frequencyPerMillion } : {}),
      ...(evidence.levelBasis === 'estimated-frequency' ? { frequencyBand: evidence.band } : {}),
      glossRevision: gloss.revision,
      quality: evidence.quality,
    },
  };
}


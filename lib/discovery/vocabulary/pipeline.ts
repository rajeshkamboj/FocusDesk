/** The anchors this date is allowed to ask about, so runs stay polite and rotate. */
export function anchorsForRun(date: string, anchorsPerRun = 6): string[] {
  const anchors = [...VOCABULARY_ANCHORS];
  if (anchors.length === 0) return [];
  const start = ((dayNumber(date) % anchors.length) + anchors.length) % anchors.length;
  const count = Math.max(1, Math.min(anchorsPerRun, anchors.length));
  return Array.from({ length: count }, (_, index) => anchors[(start + index) % anchors.length]);
}

/**
 * The glosses this run should try to approve.
 *
 * Glossed words whose approved candidate already exists at the same revision are
 * skipped — that is what makes a second run in one day almost free. The rest rotate
 * so a fresh deployment fills its reservoir over a handful of runs rather than
 * hammering three services with thirty-two words at once.
 */
export function approvalQueue(
  glosses: readonly VocabularyGloss[],
  options: { existing?: readonly KnowledgeCandidate[]; publishedWords?: readonly string[]; limit?: number } = {},
): VocabularyGloss[] {
  const published = new Set((options.publishedWords ?? []).map((word) => word.toLowerCase()));
  const existing = new Map(
    (options.existing ?? [])
      .filter((candidate) => candidate.category === 'speak-better')
      .map((candidate) => [candidate.normalizedIdentity, candidate]),
  );
  const queue: VocabularyGloss[] = [];
  for (const gloss of glosses) {
    if (published.has(gloss.word)) continue;
    const stored = existing.get(normalizeTitle(gloss.word).replace(/\s+/g, '-'))
      ?? existing.get(normalizeTitle(gloss.word));
    const storedLesson = stored?.payload?.lesson as SpeakBetterLesson | undefined;
    if (stored?.eligible && storedLesson?.discovery?.glossRevision === gloss.revision) continue;
    queue.push(gloss);
  }
  const limit = options.limit ?? queue.length;
  return queue.slice(0, Math.max(0, limit));
}

/**
 * Extract the approved lessons from the reservoir. Used by the publisher and by
 * the operator status panel; no network and no writes.
 */
export function approvedVocabularyLessons(candidates: readonly KnowledgeCandidate[]): SpeakBetterLesson[] {
  const lessons: SpeakBetterLesson[] = [];
  for (const candidate of candidates) {
    if (candidate.category !== 'speak-better') continue;
    if (!candidate.eligible || candidate.validationStatus !== 'valid') continue;
    const lesson = candidate.payload?.lesson as SpeakBetterLesson | undefined;
    if (!lesson || !lesson.id || !lesson.word?.word) continue;
    lessons.push(lesson);
  }
  return lessons;
}

async function frequencyFor(
  word: string,
  context: { fetchImpl?: typeof fetch; sleepImpl?: (ms: number) => Promise<void> },
  known?: number,
): Promise<number | undefined> {
  if (known !== undefined) return known;
  const params = new URLSearchParams({ sp: word, md: 'f', max: '1' });
  const result = await httpGet(`https://api.datamuse.com/words?${params.toString()}`, {
    fetchImpl: context.fetchImpl,
    sleepImpl: context.sleepImpl,
    attempts: 1,
    timeoutMs: 4_000,
    headers: { accept: 'application/json' },
  });
  if (!result.ok || !Array.isArray(result.json)) return undefined;
  const first = (result.json as { word?: unknown; tags?: unknown }[])[0];
  if (!first || String(first.word ?? '').toLowerCase() !== word) return undefined;
  return parseFrequencyTag(first.tags);
}

export async function runVocabularyDiscovery(options: VocabularyRunOptions): Promise<VocabularyRunOutcome> {
  const now = options.now ?? new Date();
  const nowIso = now.toISOString();
  const trigger = options.trigger ?? 'cron';
  const store = options.store ?? getCandidateStore();
  const glosses = options.glosses ?? VOCABULARY_GLOSSES;
  const publishedWords = (options.publishedWords ?? []).map((word) => word.toLowerCase());
  const reports: SourceReport[] = [];
  const notes: string[] = [];
  const approved: VocabularyApproval[] = [];
  const rejected: VocabularyRejection[] = [];
  const needsReview: VocabularyRejection[] = [];

  let existing: KnowledgeCandidate[] = [];
  try {
    existing = await store.readAll();
  } catch {
    notes.push('the candidate reservoir could not be read; approval was attempted against an empty library');
  }

  const alreadyApproved = existing.filter(
    (candidate) => candidate.category === 'speak-better' && candidate.eligible && candidate.validationStatus === 'valid',
  ).length;

  if (options.offline) {
    notes.push('offline run: no lexical source was contacted, so nothing was approved');
    reports.push({
      sourceId: 'offline',
      sourceName: 'Scheduled run',
      status: 'skipped',
      fetched: 0,
      accepted: 0,
      rejected: 0,
      duplicates: 0,
      note: 'offline mode requested',
      finishedAt: nowIso,
    });
    return {
      ranAt: nowIso,
      approved,
      rejected,
      needsReview,
      persisted: false,
      unmigrated: false,
      written: 0,
      reports,
      notes,
      summary: describeVocabularyRun({ reports, approved: 0, rejected: 0, needsReview: 0, notes }),
      reservoirApproved: alreadyApproved,
      sourceFailures: 0,
    };
  }

  /* ---- Discover --------------------------------------------------- */
  const anchors = anchorsForRun(options.date, options.anchorsPerRun ?? 6);
  const discovery = await discoverCandidates(anchors, {
    fetchImpl: options.fetchImpl,
    sleepImpl: options.sleepImpl,
  });
  reports.push({
    sourceId: 'datamuse',
    sourceName: 'Datamuse',
    status: discovery.report.status === 'ok' ? 'ok' : 'failed',
    fetched: discovery.report.fetched,
    accepted: 0,
    rejected: 0,
    duplicates: 0,
    note: discovery.report.detail,
    finishedAt: nowIso,
  });
  if (discovery.report.status === 'failed') notes.push(`Datamuse: ${discovery.report.detail}`);

  const published = new Set(publishedWords);
  const worklist: VocabularyWorkItem[] = [];
  const seenWords = new Set<string>();
  const limit = Math.max(1, options.maxWordsPerRun ?? 8);

  // Glossed words discovered by the live search come first: they are what "live
  // discovery" means. Words without a gloss are queued as needs-review.
  for (const candidate of discovery.candidates) {
    const gloss = VOCABULARY_GLOSS_BY_WORD.get(candidate.word);
    if (!gloss) {
      if (needsReview.length < 40) {
        needsReview.push({
          word: candidate.word,
          reasons: [`found via ${candidate.discoveredVia}; awaiting an editorial gloss`],
        });
      }
      continue;
    }
    if (published.has(candidate.word)) {
      rejected.push({ word: candidate.word, reasons: ['already shown to a reader; a repeat is not a new lesson'] });
      continue;
    }
    if (seenWords.has(candidate.word)) continue;
    seenWords.add(candidate.word);
    worklist.push({ word: candidate.word, discoveredVia: candidate.discoveredVia, frequencyPerMillion: candidate.frequencyPerMillion, gloss });
  }

  // Then the rotation of glosses the reservoir does not yet hold at this revision.
  for (const gloss of approvalQueue(glosses, { existing, publishedWords, limit })) {
    if (worklist.length >= limit * 2) break;
    if (seenWords.has(gloss.word)) continue;
    seenWords.add(gloss.word);
    worklist.push({ word: gloss.word, discoveredVia: 'editorial-gloss-rotation', gloss });
  }

  if (worklist.length === 0) {
    notes.push('no new word to approve today; the reservoir already holds every glossed word');
  }

  /* ---- Normalize, enrich, evaluate, validate ---------------------- */
  const drafts: CandidateDraft[] = [];
  let enriched = 0;
  let sourceFailures = 0;
  for (const item of worklist) {
    if (enriched >= limit) break;
    const gloss = item.gloss;
    const structural = glossRejections(gloss);
    if (structural.length || !gloss) {
      rejected.push({ word: item.word, reasons: structural });
      continue;
    }

    const evidence = await enrichWord(item.word, {
      fetchImpl: options.fetchImpl,
      sleepImpl: options.sleepImpl,
      frequencyPerMillion: item.frequencyPerMillion,
    });
    enriched += 1;
    sourceFailures += evidence.sources.filter((source) => source.status === 'failed').length;

    const frequency = item.frequencyPerMillion
      ?? await frequencyFor(item.word, { fetchImpl: options.fetchImpl, sleepImpl: options.sleepImpl });
    const hasLexicalDefinition = Boolean(evidence.wiktionary?.definition || evidence.freeDictionary?.definition);
    const evaluation = evaluateCandidate(gloss, { frequencyPerMillion: frequency, hasLexicalDefinition });
    const reasons = [...evaluation.rejections];
    if (!hasLexicalDefinition) {
      const asked = evidence.sources.filter((source) => source.id !== 'datamuse-related');
      reasons.push(`lexical sources did not confirm the word (${asked.map((source) => `${source.name}: ${source.detail ?? 'no answer'}`).join('; ')})`);
    }
    if (reasons.length > 0) {
      rejected.push({ word: item.word, reasons: [...new Set(reasons)] });
      continue;
    }

    const lesson = buildLesson(
      gloss,
      {
        band: evaluation.band ?? gloss.level,
        levelBasis: evaluation.levelBasis,
        frequencyPerMillion: frequency,
        quality: evaluation.quality,
        sources: evidence.sources,
        wiktionary: evidence.wiktionary,
        freeDictionary: evidence.freeDictionary,
        related: evidence.related,
      },
      options.date,
    );

    const primarySource = evidence.sources.find((source) => source.status === 'ok');
    drafts.push({
      id: `speak-better:${lesson.id}`,
      entityId: `word:${gloss.word}`,
      canonicalUrl: lesson.word.dictionary?.url ?? primarySource?.url ?? `https://en.wiktionary.org/wiki/${encodeURIComponent(gloss.word)}`,
      category: 'speak-better' as const,
      subcategory: evaluation.levelBasis,
      title: gloss.word,
      description: `${gloss.englishMeaning} ${gloss.nuance}`.slice(0, 900),
      significance: gloss.focus,
      sourceName: primarySource?.name ?? 'Wiktionary',
      attribution: evidence.sources
        .filter((source) => source.status === 'ok')
        .map((source) => `${source.name}: ${source.license}`)
        .join(' · '),
      license: evidence.sources.map((source) => source.license).join(' · '),
      aliases: [],
      subjects: [
        `word:${gloss.word}`,
        `band:${evaluation.band ?? gloss.level}`,
        `pos:${gloss.partOfSpeech}`,
        `origin:discovered`,
      ],
      payload: payloadForCollection('vocabulary', {
        lesson,
        vocabulary: {
          word: gloss.word,
          level: evaluation.band ?? gloss.level,
          levelBasis: evaluation.levelBasis,
          frequencyPerMillion: frequency ?? null,
          glossRevision: gloss.revision,
          quality: evaluation.quality,
          sources: evidence.sources.map((source) => ({
            id: source.id,
            name: source.name,
            status: source.status,
            license: source.license,
          })),
        },
      }),
      validationStatus: 'valid' as const,
      eligible: true,
      discoveredAt: nowIso,
      updatedAt: nowIso,
    });
    approved.push({
      word: gloss.word,
      level: evaluation.band ?? gloss.level,
      lesson,
      quality: evaluation.quality,
      sources: evidence.sources,
    });
  }

  /* ---- Store ------------------------------------------------------ */
  let persistence: PersistCollectionResult | null = null;
  if (!options.offline) {
    persistence = await persistCollectionRun({
      collection: 'vocabulary',
      drafts,
      reports: [],
      trigger,
      nowIso,
      store,
      strictness: 'standard',
    });
    notes.push(...persistence.notes);
  }

  const acceptedByRun = persistence?.metrics.newDiscovered ?? 0;
  const duplicates = persistence?.metrics.duplicateRejections ?? 0;
  reports.push({
    sourceId: 'editorial-gloss',
    sourceName: 'Authored gloss library',
    status: 'ok',
    fetched: worklist.length,
    accepted: acceptedByRun,
    rejected: rejected.length,
    duplicates,
    note: `${approved.length} lesson(s) assembled and verified; ${rejected.length} rejected`,
    finishedAt: nowIso,
  });

  const summary = describeVocabularyRun({
    reports,
    approved: approved.length,
    rejected: rejected.length,
    needsReview: needsReview.length,
    notes,
  });

  return {
    ranAt: nowIso,
    approved,
    rejected,
    needsReview,
    persisted: persistence?.persisted ?? false,
    unmigrated: persistence?.unmigrated ?? false,
    written: persistence?.written ?? 0,
    reports,
    notes,
    summary,
    reservoirApproved: alreadyApproved + acceptedByRun,
    sourceFailures,
  };
}

/** The one-line status a scheduler's log shows. */
export function describeVocabularyRun(input: {
  reports: readonly SourceReport[];
  approved: number;
  rejected: number;
  needsReview: number;
  notes?: readonly string[];
}): string {
  const failed = input.reports.filter((report) => report.status === 'failed').map((report) => report.sourceId);
  const parts = [
    'vocabulary discovery',
    `${input.approved} approved`,
    `${input.rejected} rejected`,
    `${input.needsReview} awaiting a gloss`,
  ];
  if (failed.length) parts.push(`failed: ${failed.join(', ')}`);
  if (input.notes?.length) parts.push(input.notes[0]);
  return parts.join(' · ');
}

/** Convenience for the operator status panel: how full the reservoir is. */
export async function vocabularyReservoirStatus(store: CandidateStore = getCandidateStore()): Promise<{
  approved: number;
  published: number;
  candidates: number;
}> {
  let candidates: KnowledgeCandidate[] = [];
  try {
    candidates = await store.readAll();
  } catch {
    candidates = [];
  }
  const vocab = candidates.filter((candidate) => candidate.category === 'speak-better');
  return {
    approved: vocab.filter((candidate) => candidate.eligible && candidate.validationStatus === 'valid').length,
    published: vocab.filter((candidate) => candidate.payload?.published === true).length,
    candidates: vocab.length,
  };
}

